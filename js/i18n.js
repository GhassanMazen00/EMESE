export const lang = () => (document.documentElement.getAttribute('lang') === 'en' ? 'en' : 'ar');
export const ui = () => UI[lang()];

function applyAttr(el, l) {
  el.getAttribute('data-i18n-attr').split(';').forEach(pair => {
    const [attr, key] = pair.split(':');
    const store = 'ar' + attr.replace(/[^a-z]/gi, '');
    if (!(store in el.dataset)) el.dataset[store] = el.getAttribute(attr) || '';
    el.setAttribute(attr, l === 'en' && EN[key] != null ? EN[key] : el.dataset[store]);
  });
}

export function applyLang(l) {
  const root = document.documentElement;
  root.setAttribute('lang', l === 'en' ? 'en' : 'ar-EG');
  root.setAttribute('dir', l === 'en' ? 'ltr' : 'rtl');
  document.querySelectorAll('[data-i18n]').forEach(el => {
    if (!('ar' in el.dataset)) el.dataset.ar = el.textContent;
    const key = el.getAttribute('data-i18n');
    el.textContent = l === 'en' && EN[key] != null ? EN[key] : el.dataset.ar;
  });
  document.querySelectorAll('[data-i18n-html]').forEach(el => {
    if (!('ar' in el.dataset)) el.dataset.ar = el.innerHTML;
    const key = el.getAttribute('data-i18n-html');
    el.innerHTML = l === 'en' && EN[key] != null ? EN[key] : el.dataset.ar;
  });
  document.querySelectorAll('[data-i18n-attr]').forEach(el => applyAttr(el, l));
  document.title = UI[l].title;
  document.dispatchEvent(new CustomEvent('langchange', { detail: l }));
}

export function setLang(l) {
  try { localStorage.setItem('emese-lang', l); } catch (e) { /* storage blocked: still switches for this visit */ }
  applyLang(l);
}
